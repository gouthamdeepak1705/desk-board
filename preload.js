const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('board', {
  load: () => ipcRenderer.invoke('board:load'),
  onChanged: (cb) => ipcRenderer.on('board:changed', (_e, d) => cb(d)),
  saveNote: (n) => ipcRenderer.invoke('note:save', n),
  deleteNote: (id) => ipcRenderer.invoke('note:delete', id),
  saveEvents: (ev) => ipcRenderer.invoke('event:save', ev),
  saveLayout: (l) => ipcRenderer.invoke('layout:save', l),
  saveConfig: (p) => ipcRenderer.invoke('config:save', p),
  windowControl: (w) => ipcRenderer.invoke('window:control', w),
  chatSend: (t, imgs) => ipcRenderer.invoke('chat:send', t, imgs),
  noteImage: (f) => ipcRenderer.invoke('note:image', f),
  chatStop: () => ipcRenderer.invoke('chat:stop'),
  chatReset: () => ipcRenderer.invoke('chat:reset'),
  onChat: (cb) => ipcRenderer.on('chat:event', (_e, d) => cb(d)),
  voiceToggle: () => ipcRenderer.send('voice:toggle'),
  onJobs: (cb) => ipcRenderer.on('jobs:state', (_e, d) => cb(d)),
  jobsList: () => ipcRenderer.invoke('jobs:list'),
  jobCancel: (id) => ipcRenderer.send('jobs:cancel', id),
  museState: () => ipcRenderer.invoke('muse:state'),
  onMuse: (cb) => ipcRenderer.on('muse:state', (_e, d) => cb(d)),
  museSend: (t) => ipcRenderer.invoke('muse:send', t),
  musePress: (id, label) => ipcRenderer.invoke('muse:press', id, label),
  museReview: () => ipcRenderer.invoke('muse:review'),
  museDecide: (label) => ipcRenderer.invoke('muse:decide', label),
  museCloseReview: () => ipcRenderer.invoke('muse:close-review'),
  museSetup: () => ipcRenderer.send('muse:setup'),
  memory: (op, args) => ipcRenderer.invoke('memory:call', op, args),
  onAgent: (cb) => ipcRenderer.on('agent:state', (_e, d) => cb(d)),
  onVoice: (cb) => ipcRenderer.on('voice:state', (_e, d) => cb(d)),
});
